"""Generate original, deterministic PDF fixtures without downloading assets."""

import argparse
import hashlib
import json
from pathlib import Path

import pymupdf

TOPICS = (
    ("bearings", "bearing noise", "Inspect the demonstration bearing housing."),
    ("pumps", "pressure loss", "Check the demonstration pump inlet."),
    ("motors", "motor overheating", "Inspect the demonstration cooling grille."),
    ("valves", "valve sticking", "Check the demonstration valve stem."),
    ("belts", "belt slipping", "Inspect the demonstration belt surface."),
    ("filters", "filter blockage", "Check the demonstration filter element."),
    ("seals", "seal leakage", "Inspect the demonstration seal seating."),
    ("gears", "gear vibration", "Check the demonstration gear alignment."),
    ("sensors", "sensor fault", "Inspect the demonstration sensor connector."),
    ("relays", "relay chatter", "Check the demonstration control circuit."),
    ("hoses", "hose abrasion", "Inspect the demonstration hose routing."),
    ("couplings", "coupling wear", "Check the demonstration coupling insert."),
    ("scanned", "scanned inspection", "Inspect the demonstration scanner fixture."),
    ("mixed", "mixed page inspection", "Check the demonstration mixed-page fixture."),
    ("russian", "перегрев подшипника", "Проверьте учебный корпус подшипника."),
)


def make_page(doc, title, body, number):
    page = doc.new_page(width=595, height=842)
    html = (
        '<div style="font-family:sans-serif;color:#173149">'
        '<p style="font-size:11pt">HARBOR EQUIPMENT / SYNTHETIC LIBRARY</p>'
        f'<h1 style="font-size:24pt">{title}</h1>'
        f'<p style="font-size:15pt;line-height:1.6">{body}</p>'
        '<p style="font-size:11pt;color:#666">'
        'Fictional portfolio example. Not an actual repair instruction.</p>'
        f'<p style="font-size:11pt">Physical PDF page {number} / 3</p></div>'
    )
    remaining, scale = page.insert_htmlbox(pymupdf.Rect(48, 48, 547, 780), html, scale_low=1)
    if remaining < 0 or scale != 1:
        raise RuntimeError("Fixture text exceeds page bounds")
    return page


def generate(output: Path) -> dict:
    """Require a fresh directory; never overwrite an existing corpus or user files."""
    output = Path(output)
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(f"Output directory is not empty: {output}")
    output.mkdir(parents=True, exist_ok=True)
    records = []
    for index, (slug, term, instruction) in enumerate(TOPICS, start=1):
        folder = output / ("scans" if slug in {"scanned", "mixed"} else "manuals")
        folder.mkdir(exist_ok=True)
        name = "учебное руководство.pdf" if slug == "russian" else f"{slug}.pdf"
        path = folder / name
        code = f"HES-{index:03d}-BX"
        pages = []
        with pymupdf.open() as doc:
            for number in range(1, 4):
                body = {
                    1: "Collection overview. Use the equipment identifier to select a document.",
                    2: f"Reference part: {code}. Fault term: {term}. {instruction}",
                    3: "Record findings in the fictional maintenance log. End of example.",
                }[number]
                page = make_page(doc, slug.upper(), body, number)
                image_only = slug == "scanned" or (slug == "mixed" and number == 2)
                if image_only:
                    raster = page.get_pixmap(dpi=144, alpha=False).tobytes("png")
                    # Replace the temporary native page with pixels only, without an OCR layer.
                    doc.delete_page(-1)
                    page = doc.new_page(width=595, height=842)
                    page.insert_image(page.rect, stream=raster)
                pages.append({"page": number, "image_only": image_only})
            doc.set_metadata({
                "title": f"Synthetic maintenance example: {slug}",
                "author": "PDF Document Search synthetic corpus",
                "subject": "Fictional portfolio demonstration",
                "creationDate": "D:20260101000000Z",
                "modDate": "D:20260101000000Z",
            })
            doc.save(path, garbage=4, deflate=True, no_new_id=True)
        records.append({
            "path": path.relative_to(output).as_posix(),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "pages": pages,
            "reference": {"code": code, "term": term, "page": 2},
        })
    manifest = {
        "schema_version": 1,
        "provenance": "Original synthetic content generated by scripts/generate_corpus.py.",
        "license": "AGPL-3.0-only",
        "page_numbering": "Physical PDF pages, 1-based",
        "documents": records,
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="New or empty output directory")
    args = parser.parse_args()
    manifest = generate(args.output)
    print(f"Generated {len(manifest['documents'])} synthetic PDFs.")


if __name__ == "__main__":
    main()
